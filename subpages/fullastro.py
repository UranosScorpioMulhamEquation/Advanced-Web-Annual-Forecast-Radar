def format_degree(deg):
    sign_idx = int(deg // 30) % 12
    rem = deg % 30
    d_int = int(rem)
    m_int = int((rem - d_int) * 60)
    return f"{d_int}° {m_int:02d}' - {zodiacs_en[sign_idx]}"

