def find_solar_return_exact(birth_jd_utc: float, target_year: int) -> float:
    natal_sun_lon = swe.calc_ut(birth_jd_utc, swe.SUN)[0][0]
    jd_start = swe.julday(target_year, 1, 1, 0.0)
    jd_end = swe.julday(target_year, 12, 31, 23.999)

    for _ in range(50):
        jd_mid = (jd_start + jd_end) / 2.0
        mid_sun_lon = swe.calc_ut(jd_mid, swe.SUN)[0][0]
        diff = (mid_sun_lon - natal_sun_lon) % 360
        if diff > 180: diff -= 360
        if diff < 0: jd_start = jd_mid
        else: jd_end = jd_mid

    return (jd_start + jd_end) / 2.0

def calculate_solar_chart(birth_date: date, birth_time_val: time, b_lat: float, b_lon: float, b_tz_str: str,
                          r_lat: float, r_lon: float, r_tz_str: str, target_year: int) -> SolarChart:
    birth_jd_utc = get_utc_julian_day(birth_date, birth_time_val, b_tz_str)
    return_jd_utc = find_solar_return_exact(birth_jd_utc, target_year)

    y, m, d, h_float = swe.revjul(return_jd_utc)
    hours = int(h_float)
    minutes = int((h_float - hours) * 60)
    seconds = int((((h_float - hours) * 60) - minutes) * 60)

    try:
        r_tz = pytz.timezone(r_tz_str)
    except Exception:
        r_tz = pytz.utc
    utc_dt = datetime.datetime(y, m, d, hours, minutes, seconds, tzinfo=pytz.utc)
    return_local = utc_dt.astimezone(r_tz)

    cusps, ascmc = swe.houses(return_jd_utc, r_lat, r_lon, b'W')
    solar_asc_deg = ascmc[0]
    solar_mc_deg = ascmc[1]
    solar_asc_sign, asc_sign_idx, _ = zodiac_info(solar_asc_deg)

    planets_to_calc = {
        "الشمس": swe.SUN, "القمر": swe.MOON, "عطارد": swe.MERCURY,
        "الزهرة": swe.VENUS, "المريخ": swe.MARS, "المشتري": swe.JUPITER,
        "زحل": swe.SATURN, "أورانوس": swe.URANUS, "نبتون": swe.NEPTUNE,
        "بلوتو": swe.PLUTO
    }

    planet_rows = []
    flags = swe.FLG_SWIEPH | swe.FLG_SPEED
    for name, p_id in planets_to_calc.items():
        coords, _ = swe.calc_ut(return_jd_utc, p_id, flags)
        lon_deg, speed = coords[0], coords[3]
        sign_name, sign_idx, deg_rem = zodiac_info(lon_deg)
        house_num = ((sign_idx - asc_sign_idx) % 12) + 1

        planet_rows.append({
            "الكوكب": name,
            "الموقع": f"{sign_name} {deg_rem:.2f}°",
            "البيت": str(house_num),
            "الحركة": "متراجع ↺" if speed < 0 else "مباشر ➔",
            "درجة_البرج": deg_rem,
            "الطول_المطلق": lon_deg
        })

    try:
        b_tz = pytz.timezone(b_tz_str)
    except Exception:
        b_tz = pytz.utc
    birth_local = datetime.datetime.combine(birth_date, birth_time_val).replace(tzinfo=b_tz)

    return SolarChart(
        birth_local=birth_local,
        return_local=return_local,
        solar_asc_deg=solar_asc_deg,
        solar_mc_deg=solar_mc_deg,
        solar_asc_sign=solar_asc_sign,
        planet_rows=planet_rows,
        house_system="Whole Sign (كل برج بيت)"
    )

def run_usm_engine_daily(birth_date: date) -> List[USMRow]:
    homo_k, eris_k, neptune_k, tolerance = 6.18, 9.3, 10.77, 0.3
    results = []
    for i in range(1, 85):
        h_dev = abs((i / homo_k) - round(i / homo_k))
        e_dev = abs((i / eris_k) - round(i / eris_k))
        n_dev = abs((i / neptune_k) - round(i / neptune_k))
        status = "CRITICAL" if (h_dev <= tolerance and e_dev <= tolerance and n_dev <= tolerance) else "Normal"
        results.append(USMRow(
            age=i, risk_date=date(birth_date.year + i, 1, 1), status=status,
            homo_deviation=h_dev, eris_deviation=e_dev, neptune_deviation=n_dev
        ))
    return results

